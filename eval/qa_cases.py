"""RAGAS 的题库 —— 问题和**人工写的参考答案**。

## 为什么参考答案必须人工写

RAGAS 的 `context_recall` 和 `context_precision` 都拿 `reference` 当真值：
「检索出来的块覆盖了参考答案里的几成」「排在前面的块有没有用」。

如果 `reference` 是模型生成的，那这个评测就变成了「**模型 A 的答案 vs 模型 B
的检索**」—— 分数反映的是两个模型的口味差多少，而不是检索好不好。
更糟的是它是自证的：模型 B 检索得好、模型 A 也跟着答得好，分数虚高而没人知道。

所以这 20 条答案是照着 `knowledge/` 里我自己写的文档**逐条核对**写下来的，
不是生成的。这也是这一天里最花时间、最不能省的一步。

## 分两组

`LITERAL` 组：问题里的词在文档里也出现。词法检索**理应**做对。
`PARAPHRASED` 组：换个说法，文档里一个原词都没有。这一组是纯词法检索的
**结构性短板**，不是 bug。

分开报是为了让分数**可解读**：一个总体 0.6 分，和「字面组 0.95 + 转述组 0.2」
说的是完全不同的两件事，而后者才能告诉你下一步该做什么。

## source 字段

标了这条题的答案**应该**出自哪一篇。它不参与 RAGAS 打分，只用来在分数难看时
回答「是检索没找对地方，还是找对了但答歪了」。
"""

