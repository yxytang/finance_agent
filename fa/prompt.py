"""system prompt 组装。

刻意做成**纯函数**：所有会变的东西都是显式参数，不在这里扫盘、不碰文件。
好处是能做指纹比对 —— 只有渲染结果真的变了才替换 `messages[0]`，否则每轮都改
会让 DeepSeek 的前缀缓存整段失效（前缀命中大约便宜 10 倍）。
"""

from fa.config import CATEGORIES, SKILL_LIST_BUDGET

PERSONA = """你是一个个人财务分析助手。

用户会拿自然语言问他的账单 ——「上个月外卖花了多少」「有没有重复扣款」。
你的回答必须**准确、可核对**，因为用户是拿它当真的。

## 三条铁律

1. **数字只能来自工具。** 任何时候要算钱、数笔数、按月分组，都调
   `query_transactions`。**绝不凭记忆或印象报数字。** 报「比上月多多少」这类
   差值时，必须把**两个原始数字一起写出来**（「6 月 7,034.22 → 7 月 8,234.56」），
   让用户能自己验算 —— 只给一个「+17.1%」，用户没法核对，而这个项目的全部
   价值就在于可核对。
2. **说不清就先问。** 时间范围或类目不明确时（「最近」是多久？「吃饭」算不算
   咖啡？），先问一句，不要猜。猜错的时间范围会给出一个数字上说得通、但
   答非所问的答案 —— 那种错误用户很难发现。
3. **复述你用的查询条件。** 回答时带上「2026-07 全月、类目=餐饮外卖」这样的
   限定条件，用户才能核对。一个光的数字没法验证。
"""

STYLE = """## 风格

- 中文回答，简洁直接，不要客套。
- 金额写成 `1,234.56`，支出为正、收入与退款为负。
- 涉及多个月或多个类目时，用表格比用句子清楚。
"""


def render_data_section() -> str:
    """数据概况 + 类目表。

    类目表**必须列出来**，因为它是固定枚举，而模型不知道这件事。不列的话它
    会自己编一个「伙食费」传进查询，拿到 0 笔，然后自信地告诉用户「你这个月
    没吃饭」。**一个错的枚举值不会报错，只会安静地返回空** —— 这是最难发现的
    一类错误，所以得从提示词这一层就堵住。
    """
    listed = "、".join(CATEGORIES)
    return (
        "## 账单数据\n\n"
        "用户的账单通过工具访问，**你不接收也不该试图读取任何文件路径**。\n\n"
        f"**类目是固定这 {len(CATEGORIES)} 个，不要自己发明新的**：\n\n"
        f"{listed}\n\n"
        "不确定数据的时间跨度、账户有哪些时，先调 `describe_data` 看一眼再回答。"
    )


def render_routing_section() -> str:
    """两类问题走两条路 —— 这是这个 agent 最容易走错的地方。

    数字问题去查账单，政策问题去查知识库。判断错的表现很隐蔽：**拿账单数据
    去回答政策问题，会给出一个看起来合理但和问题无关的数字**，而用户很难
    察觉。所以要把这个岔路口明确写出来。

    两个工具都接不住的问题（「我该不该买房」）也在这里说清楚：诚实的回答是
    「取决于 A、B、C」，不是硬找一个工具去凑一个答案。
    """
    return (
        "## 两类问题，两条路\n\n"
        "- **「我花了多少」「有没有被多扣钱」「哪家我去得最多」**\n"
        "  → 数字问题。答案必须从账单算出来：`query_transactions` /\n"
        "  `find_anomalies` / `list_subscriptions`。\n\n"
        "- **「房贷利息能抵多少个税」「应急资金该存几个月」「分期真实利率多少」**\n"
        "  → 政策/概念问题。答案在知识库里：`search_knowledge`。**这类问题\n"
        "  不要凭记忆回答**，也不要用账单数据凑。\n\n"
        "- **两边都不适用的**（「我该不该买房」）→ 诚实说明它取决于哪些因素、\n"
        "  需要用户提供什么信息，**不要硬凑一个工具**给一个看起来像答案的东西。\n\n"
        "知识库检索是纯词法的（没有语义向量），**换个说法就搜不到**。所以查的\n"
        "时候用关键词比用整句准：「专项附加扣除 房贷利息」比「我想知道我这种\n"
        "情况能少交多少税」命中率高得多。查不到就换个说法再试，两次都不行\n"
        "就直说没有。"
    )


def render_skills_section(skills) -> str:
    """skill 清单 —— 渐进披露的**第一级**：只有名字和描述，正文一个字不进。

    正文不进不是审美问题，是上下文预算问题。这份清单在 `messages[0]` 里，
    也就是**每一轮都在**。把 skill 正文全塞进来，几十个 skill 就能把窗口吃掉
    一大半，而其中绝大多数和当前问题毫无关系。

    超预算时**整条不列**，而不是把描述截半句 —— 半句话比没有更糟，模型会拿
    残缺信息去判断该不该用这个 skill。

    但省略是有代价的：没列出来的 skill，模型不知道它存在，也就永远不会用。
    这是一条真取舍，不是免费的优化。
    """
    if not skills:
        # 这里**一个字都不能提 use_skill**。在 forge 上踩过这个坑：提示词里
        # 写着「用某个工具去查」，而那个工具根本不在工具列表里，模型收到的
        # 是一条执行不了的命令，只好回一句「我这边没有」把问题挡回去。
        # 规则必须和事实同源 —— 没有 skill 就直说没有。
        return "## 可用的 skill\n\n（当前没有 skill。）"

    lines: list[str] = []
    used = 0
    for index, skill in enumerate(skills):
        line = f"- {skill.name}: {skill.description}"
        if used + len(line) + 1 > SKILL_LIST_BUDGET:
            lines.append(f"…另有 {len(skills) - index} 个 skill 因篇幅未列出。")
            break
        lines.append(line)
        used += len(line) + 1

    return (
        "## 可用的 skill\n\n"
        "这个项目预置了一些分析流程。开始回答之前先扫一遍：只要有一条和当前问题\n"
        "沾边，就先调 `use_skill` 把正文读进来再动手 —— 正文里通常是本项目对\n"
        "口径和格式的具体约定，跳过它容易按通用习惯来，然后和约定对不上。\n\n"
        "清单里只有名字和一句话描述，正文必须调 `use_skill` 才拿得到。\n\n"
        + "\n".join(lines)
    )


def _budget() -> int:
    """从 config **在调用时**读，不 import 快照 —— 测试要能 monkeypatch 它。"""
    from fa import config

    return config.SKILL_LIST_BUDGET


def render_memory_section(memories) -> str:
    """跨会话记忆 —— 用户教过的事。

    放在 prompt 的**靠后**位置，虽然它讲的是「用户是谁」、按语义该靠前。
    原因是前缀缓存：记忆会变（用户随时可能说「记住…」），而它一变，它**后面**
    的所有内容都要重新算。所以顺序按「易变的靠后」排，不按语义排。

    这个取舍有代价 —— 记忆的位置越靠后，它对模型的影响力越弱。但它值得：
    记忆本来就不该压过人设和数据结构。

    没有记忆时**整段不出现**，不输出「（暂无记忆）」。空段落只会白占 token，
    而且「暂无记忆」这四个字会让模型以为记忆功能是坏的。
    """
    if not memories:
        return ""

    lines = [f"- {m.text}" for m in memories]
    return (
        "## 关于这位用户\n\n"
        "以下是你以前记住的事。**把它们当作已知事实**，不用再问一遍；"
        "如果和当前对话里用户说的不一致，**以用户刚说的为准**。\n\n"
        + "\n".join(lines)
    )


def build_system_prompt(skills, memories=()) -> str:
    """拼出这一轮的 system prompt。

    `skills` 和 `memories` 都是**显式参数**而不是在这里现读：一是不碰文件才叫
    纯函数，二是指纹门控需要「同样输入必得同样输出」才成立 —— 如果它自己去
    读盘，门控依赖的就是一个函数体里看不见的副作用了。

    顺序固定，而且**易变的靠后**：DeepSeek 按精确 token 前缀命中缓存。skill
    清单和记忆都是会变的，放最后就只让它们自己那一段失效，前面的人设和数据
    说明照样命中。
    """
    sections = [
        PERSONA,
        render_data_section(),
        render_routing_section(),
        STYLE,
        render_memory_section(memories),
        render_skills_section(skills),
    ]
    # 空段落直接丢掉，免得在 prompt 里留下连续空行。
    return "\n\n".join(section for section in sections if section)
